#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "nc.h"

static void put_str(FILE *f, const char *s)
{
    fputc('"', f);
    for (; *s; s++) {
        if (*s == '"' || *s == '\\')
            fputc('\\', f);
        fputc(*s, f);
    }
    fputc('"', f);
}

static char *unquote(const char *v)
{
    struct nc_buf b;

    nc_buf_init(&b);
    if (*v == '"')
        v++;
    while (*v && *v != '"') {
        if (*v == '\\' && v[1])
            v++;
        nc_buf_addc(&b, *v);
        v++;
    }
    return nc_buf_take(&b);
}

static void apply(const char *name, const char *val)
{
    struct nc_sym *s = nc_sym_find(name);
    char *v;

    if (!s) {
        nc_warn("unknown symbol %s in configuration ignored", name);
        return;
    }
    s->in_config = 1;
    if (s->type == NC_STRING) {
        v = unquote(val);
        nc_sym_set_user(s, v);
        free(v);
    } else {
        nc_sym_set_user(s, val);
    }
}

int nc_conf_read(const char *path)
{
    size_t len;
    size_t pos = 0;
    size_t e;
    char *buf = nc_read_file(path, &len);
    char *line;
    char *eq;
    char *end;
    char *name;
    struct nc_sym *s;

    if (!buf)
        return -1;
    while (pos < len) {
        e = pos;
        while (e < len && buf[e] != '\n')
            e++;
        line = nc_xstrndup(buf + pos, e - pos);
        pos = e < len ? e + 1 : e;
        e = strlen(line);
        if (e > 0 && line[e - 1] == '\r')
            line[e - 1] = '\0';
        if (!strncmp(line, "CONFIG_", 7)) {
            eq = strchr(line + 7, '=');
            if (eq) {
                name = nc_xstrndup(line + 7, (size_t)(eq - line) - 7);
                apply(name, eq + 1);
                free(name);
            }
        } else if (!strncmp(line, "# CONFIG_", 9)) {
            end = strstr(line + 9, " is not set");
            if (end) {
                name = nc_xstrndup(line + 9, (size_t)(end - line) - 9);
                s = nc_sym_find(name);
                if (s && s->type == NC_BOOL) {
                    s->in_config = 1;
                    nc_sym_set_user(s, "n");
                }
                free(name);
            }
        }
        free(line);
    }
    free(buf);
    return 0;
}

int nc_conf_write(const char *path)
{
    FILE *f = fopen(path, "w");
    const struct nc_sym *s;

    if (!f) {
        nc_warn("cannot write %s", path);
        return -1;
    }
    fputs("#\n# Generated by nirconfig\n#\n", f);
    for (s = nc_sym_first(); s; s = s->lnext) {
        if (!nc_sym_active(s) || s->type == NC_UNKNOWN)
            continue;
        switch (s->type) {
        case NC_BOOL:
            if (!strcmp(s->value, "y"))
                fprintf(f, "CONFIG_%s=y\n", s->name);
            else
                fprintf(f, "# CONFIG_%s is not set\n", s->name);
            break;
        case NC_INT:
        case NC_HEX:
            fprintf(f, "CONFIG_%s=%s\n", s->name, s->value);
            break;
        case NC_STRING:
            fprintf(f, "CONFIG_%s=", s->name);
            put_str(f, s->value);
            fputc('\n', f);
            break;
        default:
            break;
        }
    }
    if (fclose(f) != 0) {
        nc_warn("error while writing %s", path);
        return -1;
    }
    return 0;
}

int nc_header_write(const char *path)
{
    FILE *f = fopen(path, "w");
    const struct nc_sym *s;

    if (!f) {
        nc_warn("cannot write %s", path);
        return -1;
    }
    fputs("#ifndef NIRCONFIG_AUTOCONF_H\n#define NIRCONFIG_AUTOCONF_H\n\n", f);
    for (s = nc_sym_first(); s; s = s->lnext) {
        if (!nc_sym_active(s) || s->type == NC_UNKNOWN)
            continue;
        switch (s->type) {
        case NC_BOOL:
            if (!strcmp(s->value, "y"))
                fprintf(f, "#define CONFIG_%s 1\n", s->name);
            break;
        case NC_INT:
        case NC_HEX:
            fprintf(f, "#define CONFIG_%s %s\n", s->name, s->value);
            break;
        case NC_STRING:
            fprintf(f, "#define CONFIG_%s ", s->name);
            put_str(f, s->value);
            fputc('\n', f);
            break;
        default:
            break;
        }
    }
    fputs("\n#endif\n", f);
    if (fclose(f) != 0) {
        nc_warn("error while writing %s", path);
        return -1;
    }
    return 0;
}
