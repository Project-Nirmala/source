#!/usr/bin/env python3
"""
Generate sys/dev/font8x16.c from an X11 PCF bitmap font (8x16, ASCII 0x20-0x7E).

    tools/gen_font.py /usr/share/fonts/X11/cyrillic/koi8x16.pcf.gz > sys/dev/font8x16.c

Source font: koi8x16 from X.Org font-misc-cyrillic, which its package documents as
"May be distributed and modified without restrictions".
"""
import gzip
import struct
import sys

PCF_BITMAPS, PCF_BDF_ENCODINGS = 8, 32

def read_pcf(path):
    raw = open(path, 'rb').read()
    if raw[:2] == b'\x1f\x8b':
        raw = gzip.decompress(raw)
    if raw[:4] != b'\x01fcp':
        raise SystemExit("not a PCF font")
    ntables, = struct.unpack_from('<I', raw, 4)
    tables = {}
    for i in range(ntables):
        typ, fmt, size, off = struct.unpack_from('<IIII', raw, 8 + 16 * i)
        tables[typ] = (fmt, off)
    return raw, tables

def main():
    raw, tables = read_pcf(sys.argv[1])

    fmt, off = tables[PCF_BDF_ENCODINGS]
    end = '>' if fmt & 4 else '<'
    minb2, maxb2, minb1, maxb1, default = struct.unpack_from(end + '5h', raw, off + 4)
    nidx = (maxb2 - minb2 + 1) * (maxb1 - minb1 + 1)
    indices = struct.unpack_from(end + '%dh' % nidx, raw, off + 14)

    fmt, off = tables[PCF_BITMAPS]
    end = '>' if fmt & 4 else '<'
    msb_first = bool(fmt & 8)
    pad = 1 << (fmt & 3)
    count, = struct.unpack_from(end + 'I', raw, off + 4)
    offsets = struct.unpack_from(end + '%di' % count, raw, off + 8)
    data = off + 8 + 4 * count + 16

    print("/*\n * SPDX-License-Identifier: CDDL-1.0 (this file); font data below is from koi8x16\n"
          " * (X.Org font-misc-cyrillic: \"May be distributed and modified without restrictions\").\n"
          " * Generated by tools/gen_font.py -- 8x16 glyphs for ASCII 0x20..0x7E, one byte per row,\n"
          " * most significant bit = leftmost pixel.\n */\n")
    print("#include <fbcon.h>\n\nconst uint8_t font8x16[FONT_GLYPHS][FONT_HEIGHT] = {")
    for code in range(0x20, 0x7F):
        idx = indices[code - minb2]
        base = data + offsets[idx]
        rows = []
        for y in range(16):
            b = raw[base + y * pad]
            if not msb_first:
                b = int('{:08b}'.format(b)[::-1], 2)
            rows.append(b)
        art = ' '.join('%02X' % r for r in rows)
        print("    /* %02X %s */ { %s }," % (code, chr(code) if chr(code) != '\\' else 'backslash',
              ', '.join('0x%02X' % r for r in rows)))
        if '--show' in sys.argv and chr(code) in 'Ag~@':
            for r in rows:
                sys.stderr.write(''.join('#' if r & (0x80 >> x) else '.' for x in range(8)) + '\n')
            sys.stderr.write('\n')
    print("};")

main()
